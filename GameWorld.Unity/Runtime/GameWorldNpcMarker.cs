using UnityEngine;

namespace GameWorld.UnityClient
{
    public interface IGameWorldInteractable
    {
        void Interact();
    }

    public sealed class GameWorldNpcMarker : MonoBehaviour, IGameWorldInteractable
    {
        [SerializeField] private string npcName = "NPC";
        [SerializeField] private string message = "Xin chào!";

        public void Interact()
        {
            Debug.Log($"{npcName}: {message}");
        }
    }
}


































































































































































